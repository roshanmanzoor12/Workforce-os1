from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    String,
    UniqueConstraint,
)
from sqlalchemy.orm import (
    Mapped,
    mapped_column,
)

from app.db.tenant_base import (
    TenantBase,
    TenantStandardModelMixin,
)


# =========================================================
# DEVICE STATUSES
# =========================================================

DEVICE_STATUS_PENDING = "pending"
DEVICE_STATUS_ACTIVE = "active"
DEVICE_STATUS_OFFLINE = "offline"
DEVICE_STATUS_DISABLED = "disabled"
DEVICE_STATUS_REVOKED = "revoked"

DEVICE_STATUSES = (
    DEVICE_STATUS_PENDING,
    DEVICE_STATUS_ACTIVE,
    DEVICE_STATUS_OFFLINE,
    DEVICE_STATUS_DISABLED,
    DEVICE_STATUS_REVOKED,
)


# =========================================================
# DEVICE MODEL
# =========================================================


class Device(
    TenantStandardModelMixin,
    TenantBase,
):
    """
    Tenant-local managed endpoint.

    Security boundaries:

    - the physical tenant database is the workspace boundary
    - no workspace_id or database-routing field is stored here
    - device_uuid is generated by trusted backend registration logic
    - agent_identifier identifies one installed agent instance
    - employee_id references only the tenant-local employees table
    """

    __tablename__ = "devices"

    __table_args__ = (
        # -------------------------------------------------
        # UNIQUE IDENTITIES
        # -------------------------------------------------

        UniqueConstraint(
            "device_uuid",
            name="uq_devices_device_uuid",
        ),

        UniqueConstraint(
            "agent_identifier",
            name="uq_devices_agent_identifier",
        ),

        # -------------------------------------------------
        # LIFECYCLE VALIDATION
        # -------------------------------------------------

        CheckConstraint(
            (
                "status IN "
                "('pending', 'active', 'offline', "
                "'disabled', 'revoked')"
            ),
            name="ck_devices_status",
        ),

        # -------------------------------------------------
        # QUERY INDEXES
        # -------------------------------------------------

        Index(
            "ix_devices_employee_id",
            "employee_id",
        ),

        Index(
            "ix_devices_status",
            "status",
        ),

        Index(
            "ix_devices_is_active",
            "is_active",
        ),

        Index(
            "ix_devices_last_seen_at",
            "last_seen_at",
        ),

        Index(
            "ix_devices_hostname",
            "hostname",
        ),
    )

    # =====================================================
    # DEVICE IDENTITY
    # =====================================================

    device_uuid: Mapped[uuid.UUID] = mapped_column(
        nullable=False,
        default=uuid.uuid4,
    )

    employee_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey(
            "employees.id",
            ondelete="SET NULL",
        ),
        nullable=True,
    )

    # =====================================================
    # MACHINE INFORMATION
    # =====================================================

    hostname: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
    )

    os_name: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
    )

    os_version: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
    )

    architecture: Mapped[str | None] = mapped_column(
        String(50),
        nullable=True,
    )

    # =====================================================
    # AGENT INFORMATION
    # =====================================================

    agent_version: Mapped[str | None] = mapped_column(
        String(50),
        nullable=True,
    )

    agent_identifier: Mapped[str | None] = mapped_column(
        String(255),
        nullable=True,
    )

    # =====================================================
    # DEVICE LIFECYCLE
    # =====================================================

    status: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        default=DEVICE_STATUS_PENDING,
    )

    is_active: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=True,
    )

    first_seen_at: Mapped[datetime | None] = mapped_column(
        DateTime(
            timezone=True
        ),
        nullable=True,
    )

    last_seen_at: Mapped[datetime | None] = mapped_column(
        DateTime(
            timezone=True
        ),
        nullable=True,
    )

    registered_at: Mapped[datetime | None] = mapped_column(
        DateTime(
            timezone=True
        ),
        nullable=True,
    )

    revoked_at: Mapped[datetime | None] = mapped_column(
        DateTime(
            timezone=True
        ),
        nullable=True,
    )

    # =====================================================
    # FUTURE MONITORING PROFILE
    # =====================================================

    monitoring_profile_id: Mapped[
        uuid.UUID | None
    ] = mapped_column(
        nullable=True,
    )


